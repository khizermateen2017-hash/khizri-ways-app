/* Update Individual Wazifa Status Badge */
window.updateFuyuzWazifaBadge = function(wid) {
  const data = window.getFuyuzData();
  const wObj = (window.FUYUZ_BOOKLET_WAZAIF || []).find(x => x.id === wid);
  if (!wObj) return;

  const badge = document.getElementById('fnCardStatusBadge_' + wid);
  const card = document.getElementById('fnCard_' + wid);
  let isDone = false;
  let progressText = 'غیر مکمل';

  // Check 7-day
  if (wObj.track_7day) {
    let count7 = 0;
    for (let d = 1; d <= 7; d++) {
      if (data.ticks7 && data.ticks7[wid + '_' + d]) count7++;
    }
    const pBadge7 = document.getElementById('fn7DayProgressBadge_' + wid);
    if (pBadge7) pBadge7.textContent = `${count7}/۷ دن`;
    if (count7 === 7) {
      isDone = true;
      progressText = '۷ دن مکمل ✓';
    } else if (count7 > 0) {
      progressText = `${count7}/۷ دن جاری`;
    }
  }

  // Check 40-day
  if (wObj.track_40day) {
    const total40 = wObj.track_40day.days_count;
    const completed40 = (data.ticks40 && data.ticks40[wid]) ? data.ticks40[wid].length : 0;
    const pBadge40 = document.getElementById('fn40DayProgressBadge_' + wid);
    if (pBadge40) pBadge40.textContent = `${completed40} / ${total40} دن مکمل`;
    if (completed40 >= total40) {
      isDone = true;
      progressText = `${total40} دن چلہ مکمل ✓`;
    } else if (completed40 > 0) {
      progressText = `${completed40}/${total40} دن جاری`;
    }
  }

  // Check Phases
  if (wObj.phases) {
    let doneP = 0;
    for (let p = 1; p <= wObj.phases.length; p++) {
      if (data.phases && data.phases[wid + '_' + p]) doneP++;
    }
    if (doneP === wObj.phases.length) {
      isDone = true;
      progressText = 'تمام مراحل مکمل ✓';
    } else if (doneP > 0) {
      progressText = `${doneP}/${wObj.phases.length} مرحلہ مکمل`;
    }
  }

  // Check Single / Walking
  if (wObj.single_day || wObj.walking) {
    if (data.single && data.single[wid]) {
      isDone = true;
      progressText = 'مکمل / جاری ✓';
    }
  }

  if (badge) {
    badge.textContent = progressText;
    if (isDone) {
      badge.style.background = '#ECFDF5';
      badge.style.color = '#065F46';
      badge.style.borderColor = '#10B981';
      if (card) card.style.borderColor = '#A7F3D0';
    } else if (progressText !== 'غیر مکمل') {
      badge.style.background = '#FEF3C7';
      badge.style.color = '#92400E';
      badge.style.borderColor = '#FDE68A';
      if (card) card.style.borderColor = '#FCD34D';
    } else {
      badge.style.background = '#F8FAFC';
      badge.style.color = '#64748B';
      badge.style.borderColor = '#CBD5E1';
      if (card) card.style.borderColor = '#E2E8F0';
    }
  }
};

/* Load Full State from LocalStorage */
window.loadFuyuzState = function() {
  const data = window.getFuyuzData();
  const wazaif = window.FUYUZ_BOOKLET_WAZAIF || [];

  wazaif.forEach(w => {
    const wid = w.id;

    // Load 7-Day Ticks
    if (w.track_7day) {
      for (let d = 1; d <= 7; d++) {
        const isChecked = Boolean(data.ticks7 && data.ticks7[wid + '_' + d]);
        const chk = document.getElementById('fnTick7_' + wid + '_' + d);
        const lbl = document.getElementById('fnDayLabel_' + wid + '_' + d);
        if (chk) chk.checked = isChecked;
        if (lbl) {
          lbl.style.background = isChecked ? '#ECFDF5' : '#FFFFFF';
          lbl.style.borderColor = isChecked ? '#10B981' : '#E2E8F0';
        }
      }
    }

    // Load 40-Day Start Date & Pills
    if (w.track_40day) {
      const total40 = w.track_40day.days_count;
      const input = document.getElementById('fnStartDate_' + wid);
      if (input) {
        if (data.startDates && data.startDates[wid]) {
          input.value = data.startDates[wid];
        } else {
          input.value = new Date().toISOString().split('T')[0];
        }
        window.updateFuyuz40DayDate(wid);
      }

      const completedDays = (data.ticks40 && data.ticks40[wid]) ? data.ticks40[wid] : [];
      for (let dayIdx = 1; dayIdx <= total40; dayIdx++) {
        const pill = document.getElementById('fnPill40_' + wid + '_' + dayIdx);
        if (pill) {
          if (completedDays.includes(dayIdx)) {
            pill.style.background = '#10B981';
            pill.style.borderColor = '#059669';
            pill.style.color = '#FFFFFF';
          } else {
            pill.style.background = '#FFFFFF';
            pill.style.borderColor = '#CBD5E1';
            pill.style.color = '#475569';
          }
        }
      }
    }

    // Load Phases
    if (w.phases) {
      for (let p = 1; p <= w.phases.length; p++) {
        const isChecked = Boolean(data.phases && data.phases[wid + '_' + p]);
        const chk = document.getElementById('fnTickPhase_' + wid + '_' + p);
        const lbl = document.getElementById('fnPhaseLabel_' + wid + '_' + p);
        if (chk) chk.checked = isChecked;
        if (lbl) {
          lbl.style.background = isChecked ? '#ECFDF5' : '#FFFFFF';
          lbl.style.borderColor = isChecked ? '#10B981' : '#E2E8F0';
        }
      }
    }

    // Load Single / Walking
    if (w.single_day || w.walking) {
      const chk = document.getElementById('fnTickSingle_' + wid);
      if (chk) {
        chk.checked = Boolean(data.single && data.single[wid]);
      }
    }

    // Load Notes
    const txt = document.getElementById('fnNoteText_' + wid);
    if (txt && data.notes && data.notes[wid]) {
      txt.value = data.notes[wid];
    }

    window.updateFuyuzWazifaBadge(wid);
  });

  window.updateFuyuzDoneCount();
};

/* Update Overall Progress Counters */
window.updateFuyuzDoneCount = function() {
  const data = window.getFuyuzData();
  const wazaif = window.FUYUZ_BOOKLET_WAZAIF || [];
  let doneCount = 0;

  wazaif.forEach(w => {
    const wid = w.id;
    let hasProgress = false;

    if (w.track_7day) {
      for (let d = 1; d <= 7; d++) {
        if (data.ticks7 && data.ticks7[wid + '_' + d]) hasProgress = true;
      }
    }
    if (w.track_40day) {
      if (data.ticks40 && data.ticks40[wid] && data.ticks40[wid].length > 0) hasProgress = true;
    }
    if (w.phases) {
      for (let p = 1; p <= w.phases.length; p++) {
        if (data.phases && data.phases[wid + '_' + p]) hasProgress = true;
      }
    }
    if ((w.single_day || w.walking) && data.single && data.single[wid]) {
      hasProgress = true;
    }

    if (hasProgress) doneCount++;
  });

  const total = wazaif.length;
  const doneEl = document.getElementById('fnDoneCount');
  if (doneEl) doneEl.textContent = doneCount;

  const remEl = document.getElementById('fnRemainingCount');
  if (remEl) remEl.textContent = total - doneCount;

  const bar = document.getElementById('fnProgressBar');
  if (bar) {
    const pct = Math.round((doneCount / total) * 100);
    bar.style.width = pct + '%';
  }
};

